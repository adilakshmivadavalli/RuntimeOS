-- Judge-facing comparison queries. Values returned here are actual data queries;
-- external benchmark scores must only be populated after executing the benchmark adapters.

SELECT GOVERNANCE_LEVEL,
       COUNT(*) AS DECISIONS,
       AVG(RISK_SCORE) AS AVG_RISK,
       AVG(HARM_PROBABILITY) AS AVG_P_HARM,
       COUNT_IF(DECISION IN ('BLOCK','QUARANTINE')) AS HARD_STOPS,
       COUNT_IF(DECISION IN ('ESCALATE','STEP_UP','DUAL_CONTROL','DEFER','DRY_RUN')) AS HUMAN_OR_DEFERRED
FROM RUNTIMEOS_HACK.RISK.AGENT_ACTIONS
GROUP BY GOVERNANCE_LEVEL
ORDER BY CASE GOVERNANCE_LEVEL WHEN 'OFF' THEN 0 WHEN 'LOW' THEN 1 WHEN 'MEDIUM' THEN 2 ELSE 3 END;

SELECT *
FROM RUNTIMEOS_HACK.RISK.GOVERNANCE_SCENARIOS
ORDER BY SCENARIO_ID;
