-- RuntimeOS / Snowflake CoCo Hackathon bootstrap
CREATE DATABASE IF NOT EXISTS RUNTIMEOS_HACK;
CREATE SCHEMA IF NOT EXISTS RUNTIMEOS_HACK.RISK;

CREATE OR REPLACE FILE FORMAT RUNTIMEOS_HACK.RISK.CSV_FMT
  TYPE = CSV
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('', 'NULL');

CREATE OR REPLACE STAGE RUNTIMEOS_HACK.RISK.RAW_DATA;

CREATE OR REPLACE TABLE RUNTIMEOS_HACK.RISK.CUSTOMERS (
  CUSTOMER_ID VARCHAR, CUSTOMER_NAME VARCHAR, CUSTOMER_SEGMENT VARCHAR,
  HOME_COUNTRY VARCHAR, RISK_TIER VARCHAR, KYC_STATUS VARCHAR
);

CREATE OR REPLACE TABLE RUNTIMEOS_HACK.RISK.ACCOUNTS (
  ACCOUNT_ID VARCHAR, CUSTOMER_ID VARCHAR, ACCOUNT_TYPE VARCHAR, CURRENCY VARCHAR,
  BALANCE_INR NUMBER(18,2), STATUS VARCHAR
);

CREATE OR REPLACE TABLE RUNTIMEOS_HACK.RISK.TRANSACTIONS (
  TRANSACTION_ID VARCHAR, TIMESTAMP TIMESTAMP_NTZ, ACCOUNT_ID VARCHAR, CUSTOMER_ID VARCHAR,
  AMOUNT_INR NUMBER(18,2), CURRENCY VARCHAR, MERCHANT_ID VARCHAR, MERCHANT_CATEGORY VARCHAR,
  CHANNEL VARCHAR, COUNTRY VARCHAR, BENEFICIARY_ID VARCHAR, IS_NEW_BENEFICIARY BOOLEAN,
  IS_FRAUD_LABEL BOOLEAN, TRANSACTION_STATUS VARCHAR, RISK_SCORE NUMBER(5,0),
  RISK_LEVEL VARCHAR, RISK_SIGNALS VARCHAR
);

CREATE OR REPLACE TABLE RUNTIMEOS_HACK.RISK.REGULATORY_KNOWLEDGE (
  DOC_ID VARCHAR, DOCUMENT_NAME VARCHAR, TOPIC VARCHAR, SECTION_HINT VARCHAR,
  GUIDANCE_SUMMARY VARCHAR, SOURCE_URL VARCHAR, NOTE VARCHAR
);

CREATE OR REPLACE TABLE RUNTIMEOS_HACK.RISK.AGENT_ACTIONS (
  DECISION_ID VARCHAR, TIMESTAMP TIMESTAMP_NTZ, AGENT_ID VARCHAR, ACTION VARCHAR, RESOURCE VARCHAR,
  PURPOSE VARCHAR, RISK_SCORE NUMBER(5,0), DECISION VARCHAR, POLICY_ID VARCHAR,
  CONTAINS_PII BOOLEAN, EXTERNAL_DESTINATION BOOLEAN, REASON VARCHAR,
  GOVERNANCE_LEVEL VARCHAR, HARM_PROBABILITY FLOAT, PROVENANCE_VERIFIED BOOLEAN,
  TOOL_METADATA_HASH VARCHAR, DELEGATION_SCOPE NUMBER(18,2), AUDIT_HASH VARCHAR
);

CREATE OR REPLACE TABLE RUNTIMEOS_HACK.RISK.GOVERNANCE_SCENARIOS (
  SCENARIO_ID VARCHAR, DOMAIN VARCHAR, DATASET VARCHAR, ATTACK VARCHAR,
  LOW_OUTCOME VARCHAR, MEDIUM_OUTCOME VARCHAR, HIGH_OUTCOME VARCHAR
);
