CREATE OR REPLACE VIEW RUNTIMEOS_HACK.RISK.RISK_TRANSACTIONS AS
WITH enriched AS (
  SELECT
    t.*,
    COUNT(*) OVER (
      PARTITION BY t.ACCOUNT_ID
      ORDER BY t.TIMESTAMP
      RANGE BETWEEN INTERVAL '1 HOUR' PRECEDING AND CURRENT ROW
    ) AS TXN_VELOCITY_1H,
    AVG(t.AMOUNT_INR) OVER (PARTITION BY t.ACCOUNT_ID) AS ACCOUNT_AVG_AMOUNT,
    CASE WHEN t.COUNTRY <> 'IN' THEN TRUE ELSE FALSE END AS CROSS_BORDER_SIGNAL,
    CASE WHEN t.AMOUNT_INR >= 100000 THEN TRUE ELSE FALSE END AS HIGH_VALUE_SIGNAL
  FROM RUNTIMEOS_HACK.RISK.TRANSACTIONS t
)
SELECT
  e.*,
  CASE WHEN e.RISK_SCORE >= 80 THEN 'CRITICAL'
       WHEN e.RISK_SCORE >= 60 THEN 'HIGH'
       WHEN e.RISK_SCORE >= 35 THEN 'MEDIUM'
       ELSE 'LOW' END AS COMPUTED_RISK_LEVEL,
  CASE WHEN e.IS_NEW_BENEFICIARY OR e.COUNTRY <> 'IN' OR e.AMOUNT_INR >= 100000 OR e.TXN_VELOCITY_1H >= 5
       THEN TRUE ELSE FALSE END AS BEHAVIORAL_SIGNAL,
  CASE WHEN e.TXN_VELOCITY_1H >= 5 THEN 'velocity_anomaly' END AS VELOCITY_SIGNAL
FROM enriched e;

CREATE OR REPLACE VIEW RUNTIMEOS_HACK.RISK.DAILY_ACTIVITY AS
SELECT
  DATE_TRUNC('DAY', TIMESTAMP) AS DAY,
  COUNT(*) AS TRANSACTION_COUNT,
  SUM(AMOUNT_INR) AS TOTAL_VALUE_INR,
  AVG(RISK_SCORE) AS AVG_RISK_SCORE,
  SUM(IFF(IS_FRAUD_LABEL, 1, 0)) AS KNOWN_FRAUD_LABELS
FROM RUNTIMEOS_HACK.RISK.TRANSACTIONS
GROUP BY 1;

CREATE OR REPLACE VIEW RUNTIMEOS_HACK.RISK.REGULATORY_SEARCH_SOURCE AS
SELECT DOC_ID, DOCUMENT_NAME, TOPIC, SECTION_HINT, GUIDANCE_SUMMARY, SOURCE_URL, NOTE,
       CONCAT(DOCUMENT_NAME, ' | ', TOPIC, ' | ', SECTION_HINT, ' | ', GUIDANCE_SUMMARY) AS CHUNK
FROM RUNTIMEOS_HACK.RISK.REGULATORY_KNOWLEDGE;
