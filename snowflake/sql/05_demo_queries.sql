-- Judge-ready queries

-- 1) High-risk transaction feed
SELECT TRANSACTION_ID, TIMESTAMP, CUSTOMER_ID, AMOUNT_INR, COUNTRY,
       IS_NEW_BENEFICIARY, RISK_SCORE, RISK_LEVEL, RISK_SIGNALS
FROM RUNTIMEOS_HACK.RISK.RISK_TRANSACTIONS
WHERE RISK_SCORE >= 80
ORDER BY RISK_SCORE DESC, AMOUNT_INR DESC
LIMIT 20;

-- 2) Top customers by risk value
SELECT CUSTOMER_ID, COUNT(*) AS TXNS, SUM(AMOUNT_INR) AS VALUE_INR,
       AVG(RISK_SCORE) AS AVG_RISK
FROM RUNTIMEOS_HACK.RISK.RISK_TRANSACTIONS
WHERE TIMESTAMP >= DATEADD(DAY, -1, CURRENT_TIMESTAMP())
GROUP BY CUSTOMER_ID
ORDER BY AVG_RISK DESC, VALUE_INR DESC
LIMIT 20;

-- 3) Cross-border + new-beneficiary signal
SELECT *
FROM RUNTIMEOS_HACK.RISK.RISK_TRANSACTIONS
WHERE COUNTRY <> 'IN' AND IS_NEW_BENEFICIARY = TRUE
ORDER BY RISK_SCORE DESC
LIMIT 20;

-- 4) Governance-ready audit extract
SELECT DECISION_ID, TIMESTAMP, AGENT_ID, ACTION, RESOURCE, PURPOSE,
       RISK_SCORE, DECISION, POLICY_ID, CONTAINS_PII, EXTERNAL_DESTINATION, REASON
FROM RUNTIMEOS_HACK.RISK.AGENT_ACTIONS
ORDER BY TIMESTAMP DESC
LIMIT 100;

-- 5) Semantic view example
SELECT * FROM SEMANTIC_VIEW(
  RUNTIMEOS_HACK.RISK.RISK_INTELLIGENCE
  METRICS transactions.TRANSACTION_COUNT, transactions.TOTAL_VALUE_INR, transactions.AVERAGE_RISK_SCORE
  DIMENSIONS transactions.RISK_LEVEL
)
ORDER BY RISK_LEVEL;
